function decodeFont(hexWithWhitespace: string): Uint8Array {
  const hex = hexWithWhitespace.replace(/\s/gu, "");
  if (hex.length !== 4096) throw new Error("default P8SCII font data is corrupt");
  const bytes = new Uint8Array(2048);
  for (let index = 0; index < bytes.length; index += 1) {
    const value = Number.parseInt(hex.slice(index * 2, index * 2 + 2), 16);
    if (!Number.isInteger(value)) throw new Error("default P8SCII font data is corrupt");
    bytes[index] = value;
  }
  return bytes;
}

